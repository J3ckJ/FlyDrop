export const STRINGS = { ru, en };

export function detectLanguage() {
  try {
    const saved = localStorage.getItem('flydrop-lang');
    if (saved === 'en' || saved === 'ru') return saved;
  } catch { /* Private mode can block storage. */ }
  return 'ru';
}

export function translate(lang, key, vars) {
  const dict = STRINGS[lang] || STRINGS.ru;
  let text = dict[key] ?? STRINGS.ru[key] ?? key;
  if (typeof text !== 'string') return text;
  if (vars) for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
  return text;
}

export function localize(lang, text) {
  if (!text || lang !== 'en') return text;
  return en.errors[text] || text;
}

export function applyDocument(lang) {
  const dict = STRINGS[lang] || STRINGS.ru;
  document.documentElement.lang = lang === 'en' ? 'en' : 'ru';
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const value = dict[element.dataset.i18n];
    if (typeof value === 'string') element.textContent = value;
  });
  document.querySelectorAll('[data-i18n-html]').forEach(element => {
    const value = dict[element.dataset.i18nHtml];
    if (typeof value === 'string') element.innerHTML = value;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
    const value = dict[element.dataset.i18nPlaceholder];
    if (typeof value === 'string') element.placeholder = value;
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(element => {
    const value = dict[element.dataset.i18nAria];
    if (typeof value === 'string') element.setAttribute('aria-label', value);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(element => {
    const value = dict[element.dataset.i18nTitle];
    if (typeof value === 'string') element.title = value;
  });
  if (dict['meta.title']) document.title = dict['meta.title'];
  const description = document.querySelector('meta[name="description"]');
  if (description && dict['meta.description']) description.content = dict['meta.description'];
  for (const [name, href] of Object.entries(CONTACTS)) {
    document.querySelectorAll(`[data-contact="${name}"]`).forEach(link => { link.href = href; });
  }
}
